    static boolean contains(double longitude, double latitude) {
        if (longitude < 72 || longitude > 138 || latitude < 0.8 || latitude > 56) {
            return false;
        }
        // Small coastal regions are absent from the simplified outlines.
        if ((longitude >= 113.8 && longitude <= 114.5 && latitude >= 22.1 && latitude <= 22.6)
                || (longitude >= 113.5 && longitude <= 113.65 && latitude >= 22.05 && latitude <= 22.25)) {
            return true;
        }
        for (double[][] polygon : POLYGONS) {
            boolean inside = false;
            for (int i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
                double[] a = polygon[i];
                double[] b = polygon[j];
                if ((a[1] > latitude) != (b[1] > latitude)
                        && longitude < (b[0] - a[0]) * (latitude - a[1]) / (b[1] - a[1]) + a[0]) {
                    inside = !inside;
                }
                // Allow for BD/GCJ offsets and a small coastline simplification tolerance.
                double dx = b[0] - a[0];
                double dy = b[1] - a[1];
                double lengthSquared = dx * dx + dy * dy;
                double t = lengthSquared == 0 ? 0
                        : Math.max(0, Math.min(1, ((longitude - a[0]) * dx + (latitude - a[1]) * dy) / lengthSquared));
                if (Math.hypot(longitude - a[0] - t * dx, latitude - a[1] - t * dy) <= 0.03) {
                    return true;
                }
            }
            if (inside) {
                return true;
            }
        }
        return false;
    }

